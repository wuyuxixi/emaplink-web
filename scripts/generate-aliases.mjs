import fs from 'node:fs/promises';
import path from 'node:path';
import matter from 'gray-matter';

const ROOT = path.resolve(import.meta.dirname, '..');
const DIST = path.join(ROOT, 'dist');
const SITE = 'https://www.emaplink.com.cn';

const mainRedirects = new Map([
  ['index.html', '/'],
  ['products-insert.html', '/products/zsac-gateway/'],
  ['products-app.html', '/products/zsac-server/'],
  ['products-model.html', '/products/zsac-crypto-module/'],
  ['products-dynamic.html', '/products/zsac-otp/'],
  ['programme-insert.html', '/solutions/multi-terminal-access/'],
  ['programme-interactive.html', '/solutions/data-exchange/'],
  ['programme-app.html', '/solutions/app-protection/'],
  ['about.html', '/about/'],
  ['about1.html', '/about/culture/'],
  ['about2.html', '/about/honors/'],
  ['industry-case.html', '/about/cases/'],
  ['contact.html', '/contact/'],
  ['news.html', '/news/'],
]);

const excludedRedirects = new Map([
  ['products-video.html', '/#products'],
  ['products-safe.html', '/#products'],
  ['programme-food.html', '/#solutions'],
  ['programme-drug.html', '/#solutions'],
  ['hezuo1.html', '/about/'],
  ['news-report.html', '/news/'],
  ...[1, 2, 3, 4, 5, 6, 7].map((id) => [`report-details${id}.html`, '/about/cases/']),
]);

function aliasHtml(target) {
  const canonical = new URL(target, SITE).href;
  return `<!doctype html>
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>页面已迁移｜联易软件</title>
  <link rel="canonical" href="${canonical}">
  <meta name="robots" content="noindex,follow">
  <meta http-equiv="refresh" content="0; url=${target}">
  <script>location.replace(${JSON.stringify(target)});</script>
</head>
<body style="font-family:system-ui,sans-serif;padding:2rem;line-height:1.8;color:#132433">
  <p>页面已迁移，正在前往 <a href="${target}">新页面</a>。</p>
</body>
</html>
`;
}

async function writeAlias(oldPath, target) {
  const file = path.join(DIST, oldPath);
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, aliasHtml(target), 'utf8');
}

async function main() {
  await fs.access(DIST).catch(() => {
    throw new Error('dist/ not found. Run `pnpm build` first.');
  });

  const legacy = JSON.parse(
    await fs.readFile(path.join(ROOT, 'src', 'data', 'legacy-news.json'), 'utf8'),
  );

  const mdDir = path.join(ROOT, 'src', 'content', 'news');
  const mdFiles = (await fs.readdir(mdDir)).filter((file) => file.endsWith('.md'));
  const mdByLegacy = new Map();
  for (const file of mdFiles) {
    const raw = await fs.readFile(path.join(mdDir, file), 'utf8');
    const parsed = matter(raw);
    if (parsed.data.legacyPath) {
      mdByLegacy.set(parsed.data.legacyPath, file.replace(/\.md$/, ''));
    }
  }

  const redirects = [];

  for (const [oldPath, target] of mainRedirects) {
    if (oldPath === 'index.html') {
      redirects.push({ from: `/${oldPath}`, to: target });
      continue;
    }
    await writeAlias(oldPath, target);
    redirects.push({ from: `/${oldPath}`, to: target });
  }

  for (const [oldPath, target] of excludedRedirects) {
    await writeAlias(oldPath, target);
    redirects.push({ from: `/${oldPath}`, to: target });
  }

  for (const item of legacy) {
    const slug = mdByLegacy.get(item.legacyPath);
    const target = slug ? `/news/${slug}/` : '/news/';
    await writeAlias(item.legacyPath, target);
    redirects.push({ from: `/${item.legacyPath}`, to: target });
  }

  const redirectsFile = ['# Generated by scripts/generate-aliases.mjs', ...redirects.map((item) => `${item.from} ${item.to} 301`)].join('\n');
  await fs.writeFile(path.join(DIST, '_redirects'), `${redirectsFile}\n`, 'utf8');

  const rules = redirects
    .filter((item) => item.from !== '/')
    .map(
      (item) => `        <rule name="redirect ${item.from}">
          <match url="^${item.from.replace(/^\//, '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$" />
          <action type="Redirect" url="${item.to}" redirectType="Permanent" />
        </rule>`,
    )
    .join('\n');

  const webConfig = `<?xml version="1.0" encoding="UTF-8"?>
<configuration>
  <system.webServer>
    <rewrite>
      <rules>
${rules}
      </rules>
    </rewrite>
  </system.webServer>
</configuration>
`;
  await fs.writeFile(path.join(DIST, 'web.config'), webConfig, 'utf8');

  console.log(
    `generate-aliases: ${redirects.length} legacy URLs (${mdByLegacy.size} published news) -> dist`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
